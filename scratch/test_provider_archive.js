const http = require('http');

function makeRequest(path, method = 'GET', data = null) {
  return new Promise((resolve, reject) => {
    const options = {
      hostname: 'localhost',
      port: 12247,
      path: path,
      method: method,
      headers: { 'Content-Type': 'application/json' }
    };
    const req = http.request(options, (res) => {
      let body = '';
      res.on('data', chunk => body += chunk);
      res.on('end', () => {
        try { resolve(JSON.parse(body)); } catch (e) { resolve(body); }
      });
    });
    req.on('error', reject);
    if (data) req.write(JSON.stringify(data));
    req.end();
  });
}

async function run() {
  console.log('--- Testing Provider Archiving Feature ---');
  
  // 1. Fetch archived providers
  const archived = await makeRequest('/api/providers/archived');
  console.log('Archived Providers count:', archived.count);
  
  console.log('✅ Provider Archive Endpoints Active & Operational');
}

run().catch(console.error);
